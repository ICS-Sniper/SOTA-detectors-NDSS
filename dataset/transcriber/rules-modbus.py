import struct

def to_float(vars):
    # Ignore if any value is none
    if vars[0] is None or vars[1] is None:
        return None

    # Convert to float
    bytestr = vars[0].to_bytes(2, "big") + vars[1].to_bytes(2, "big")
    return struct.unpack("!f", bytestr)[0]


def strip_hmi_prefix(tag):
    if tag.startswith("HMI."):
        return tag[4:]
    return tag


